/**
 * Birthday lists the briefing reads from.
 *
 * These are committed data, not a live feed: Facebook has no birthday API or
 * iCal export, and the deployment target's filesystem is read-only, so there is
 * nothing to fetch and nowhere to cache. Refreshing means exporting a new list
 * and editing this file.
 *
 * Facebook never exposes a friend's birth year, so every entry is `MM-DD` only
 * and no age can be shown. Names are taken from the export verbatim.
 *
 * The two lists are merged and de-duplicated at read time by
 * `lib/providers/birthdays/birthday-list.ts`, so the same person appearing in
 * both is fine — add to whichever list they came from and let the merge sort it
 * out.
 */

export type OccasionKind = "birthday" | "anniversary";

export interface BirthdayRecord {
  /** Display name, as it appeared in the source. */
  name: string;
  /** `MM-DD`. No year: these are recurring dates, not instants. */
  on: string;
  /** Defaults to "birthday". */
  kind?: OccasionKind;
  /**
   * Year of birth, or of the wedding. Only the family list carries one, so only
   * those rows can show an age or a count of years.
   */
  since?: number;
  /**
   * Year of death. Its presence turns the row into a remembrance: the card
   * shows the span of years lived and never an age, because the person is not
   * having a birthday.
   */
  died?: number;
  /**
   * Numeric Facebook profile id, used to build a profile link. Setting this on
   * a family record is also how that person is tied to their Facebook entry, so
   * the two collapse into one row even when the names or dates disagree.
   */
  facebookId?: string;
  /** Optional note shown under the name, e.g. a maiden name. */
  note?: string;
}

